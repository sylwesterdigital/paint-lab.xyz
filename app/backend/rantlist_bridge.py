"""Optional signed, narrowly scoped Paint Lab -> Rantlist #lobby relay.

This is an outbound *service bot* integration, not Rantlist user impersonation.
No external calls are performed until the painter explicitly chooses Share.
The destination is intentionally pinned to Rantlist HTTPS to avoid SSRF and
credential leaks via redirects. Rantlist must implement the documented receiver.
"""
from __future__ import annotations
import hashlib,hmac,json,os,time,urllib.error,urllib.parse,urllib.request

DEFAULT_URL='https://rantlist.me/api/integrations/paint-lab/publications'

class BridgeError(Exception):
    pass


def settings():
    secret=os.environ.get('PAINT_LAB_RANTLIST_BRIDGE_SECRET','')
    url=os.environ.get('PAINT_LAB_RANTLIST_BRIDGE_URL',DEFAULT_URL)
    parsed=urllib.parse.urlsplit(url)
    try:
        valid=(parsed.scheme=='https' and parsed.hostname=='rantlist.me' and parsed.port in (None,443)
               and parsed.path=='/api/integrations/paint-lab/publications'
               and not parsed.username and not parsed.password and not parsed.query and not parsed.fragment)
    except ValueError:
        valid=False
    return url,secret,valid and len(secret)>=32


def enabled():
    return settings()[2]


class _RejectRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self,request,fp,code,msg,headers,newurl):
        return None


def send_publication(token,title):
    """Post a prevalidated public publication. Returns Rantlist's confirmed message ID."""
    url,secret,ready=settings()
    if not ready:raise BridgeError('Rantlist bridge is not configured')
    # Published token is generated by Paint Lab, not caller-controlled URL text.
    payload={'version':1,'destination':'lobby','publication_id':token,
             'title':title[:90],'url':'https://paint-lab.xyz/p/'+token}
    body=json.dumps(payload,separators=(',',':'),ensure_ascii=False).encode('utf-8')
    timestamp=str(int(time.time()))
    signature=hmac.new(secret.encode('utf-8'),timestamp.encode('ascii')+b'\n'+body,hashlib.sha256).hexdigest()
    req=urllib.request.Request(url,body,method='POST',headers={
        'Content-Type':'application/json','Accept':'application/json',
        'X-Paint-Lab-Timestamp':timestamp,'X-Paint-Lab-Signature':'sha256='+signature,
        'X-Paint-Lab-Idempotency-Key':token})
    try:
        with urllib.request.build_opener(_RejectRedirect).open(req,timeout=8) as response:
            if response.status not in (200,201):raise BridgeError('Rantlist did not accept the share')
            raw=response.read(8193)
            if len(raw)>8192:raise BridgeError('Unexpected Rantlist response')
            result=json.loads(raw)
    except (urllib.error.URLError,TimeoutError,OSError,ValueError) as exc:
        raise BridgeError('Rantlist bridge could not confirm delivery') from exc
    if not isinstance(result,dict) or result.get('ok') is not True or result.get('channel')!='lobby':
        raise BridgeError('Rantlist did not confirm a #lobby message')
    message_id=result.get('message_id')
    if not isinstance(message_id,str) or not (8<=len(message_id)<=100):
        raise BridgeError('Missing verified Rantlist message identifier')
    return message_id
